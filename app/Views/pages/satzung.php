            <section
                class="statute-paragraph"
                id="paragraph-1"
            >
                <h2>§1 Name, Sitz und Geschäftsjahr</h2>

                <p>
                    Der Verein führt den Namen MMIG46.
                </p>

                <p>
                    Er soll im November 1999 in das Vereinsregister am
                    Amtsgericht Essen eingetragen; nach der Eintragung
                    lautet der Name
                </p>

                <p>
                    <strong>MMIG46 e.V.</strong>
                </p>

                <p>
                    Der Verein hat seinen Sitz in Essen.
                </p>

                <p>
                    Das Geschäftsjahr des Vereins ist das Kalenderjahr.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-2"
            >
                <h2>§ 2 Grundlagen</h2>

                <p>
                    Der Verein ist ein Zusammenschluß von Besitzern,
                    Piloten, Freunden und Förderern des Flugzeugmusters
                    Piper PA46 Malibu/Mirage.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-3"
            >
                <h2>§ 3 Zielsetzung</h2>

                <p>
                    Der Verein verfolgt als Hauptziel den Betrieb, die
                    Werterhaltung und Pflege des Flugzeugmusters PA46 im
                    Sinne optimaler Betriebsbereitschaft. Die Mitglieder
                    des Vereins wollen das Verständnis für die PA46 als
                    beispielhafte Realisation einer technischen Idee
                    fördern.
                </p>

                <p>
                    Weitere Ziele liegen auf dem Gebiet des Flugbetriebs
                    im weitesten Sinne, in der Durchführung von
                    Flugschulung und Sicherheitstraining, der generellen
                    Erhöhung der Flugsicherheit und bewußterem,
                    energiesparendem Fliegen sowie in der Förderung des
                    Nachwuchses und in der Pflege sportlicher,
                    touristischer und gesellschaftlicher Belange.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-4"
            >
                <h2>§ 4 Aufgaben der MMIG46</h2>

                <p>
                    Zur Erfüllung der Aufgaben des Vereins richtet sich
                    die Vereinsarbeit vorrangig auf folgende Punkte aus:
                </p>

                <ul>
                    <li>
                        Ansprache möglichst aller europäischen PA46
                        Besitzer und Piloten auf die Ziele des Vereins
                        hin,
                    </li>

                    <li>
                        Erfassung aller europäischen PA46 , Erstellung
                        und Pflege eines Registers,
                    </li>

                    <li>
                        Einrichtung und Führung eines Archivs
                        (PA46-Historie),
                    </li>

                    <li>Organisation von Veranstaltungen,</li>

                    <li>
                        Engagement zur möglichst vollständigen
                        Ersatzteilversorgung aus dem Hause Piper oder,
                        wenn nicht anders möglich, aus anderen Quellen,
                    </li>

                    <li>
                        Hilfe beim Restaurieren im Sinne der
                        Werterhaltung der Flugzeuge. Eventuelle
                        Bereitstellung von spezifischem Werkzeug,
                        Hilfsmitteln und Anweisungen.
                    </li>

                    <li>Erstellung einer Internet Homepage und</li>

                    <li>
                        Erstellen regelmäßiger Beiträge zur
                        amerikanischen MMOPA
                    </li>
                </ul>

                <p>
                    Vereins-Zeitschrift (Vereinsinformation) mit den
                    Schwerpunkten:
                </p>

                <ul>
                    <li>Vereinsaktivitäten</li>
                    <li>Archiv (Einblicke)</li>
                    <li>
                        Fachkommentar ?Technik? (Anleitungen und
                        Erläuterungen)
                    </li>
                    <li>Hinweise zur Ersatzteilversorgung</li>
                    <li>Pressespiegel</li>
                    <li>Ankauf-/Verkaufs-Anzeigen</li>
                </ul>

                <p>
                    Der Verein ist im Rahmen seiner Ziele und Aufgaben
                    selbstlos tätig; er verfolgt nicht in erster Linie
                    eigenwirtschaftliche Zwecke. Mittel des Vereins
                    dürfen nur für die satzungsmäßigen Zwecke verwendet
                    werden. Die Mitglieder erhalten keine Zuwendungen
                    aus Mitteln des Vereins. Es darf keine Person durch
                    Ausgaben, die dem Zweck und den Zielen des Vereins
                    fremd sind, oder durch unverhältnismäßig hohe
                    Vergütungen begünstigt werden.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-5"
            >
                <h2>§ 5 Mitgliedschaft</h2>

                <p>Der Verein hat</p>

                <p>a) ordentliche Mitglieder</p>

                <p>assoziierte Mitglieder</p>

                <p>fördernde Firmenmitglieder</p>

                <p>gegebenenfalls Ehrenmitglieder</p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-6"
            >
                <h2>§ 6 Mitglieder</h2>

                <h3>a) ordentliche Mitglieder</h3>

                <p>
                    Mitglied im Verein kann jeder Besitzer oder Pilot
                    einer PA46 werden.
                </p>

                <h3>assoziierte Mitglieder</h3>

                <p>
                    Desweiteren kann sich jede natürliche Person um eine
                    Mitgliedschaft bewerben, die flugsportlich oder
                    technisch im allgemeinen und an PA 46 Flugzeugen
                    speziell interessiert ist. Alle Piloten anderer
                    high performance Aircraft wie C 210 oder Mooney
                    oder zukünftige Malibu/Mirage Piloten sind ebenfalls
                    willkommen.
                </p>

                <h3>fördernde Mitglieder</h3>

                <p>
                    Die Mitgliedschaft als förderndes Mitglied können
                    solche Firmen und Institutionen erhalten, die sich
                    um den Betrieb der PA46 verdient machen oder gemacht
                    haben.
                </p>

                <h3>Ehrenmitglieder</h3>

                <p>
                    Die Mitgliederversammlung ist berechtigt,
                    Persönlichkeiten, die sich um den Flugzeugtyp PA46
                    besondere Verdienste erworben haben, zu
                    Ehrenmitgliedern zu wählen.
                </p>

                <p>
                    Ehrenmitglieder besitzen des Status von assoziierten
                    Mitgliedern, genießen alle Rechte der Mitglieder,
                    haben aber keinen Beitrag zu zahlen.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-7"
            >
                <h2>§ 7 Aufnahme von Mitgliedern</h2>

                <p>
                    Ein Aufnahmeantrag ist schriftlich mittels des
                    vorgesehenen Formulars an den Vorstand zu richten.
                    Bei beschränkt Geschäftsfähigen, insbesondere
                    Minderjährigen, ist der Antrag auch von den
                    gesetzlichen Vertretern zu unterschreiben. Diese
                    verpflichten sich - mehrere gesamtschuldnerisch -
                    zur Zahlung der Mitgliedsbeiträge für den beschränkt
                    Geschäftsfähigen.
                </p>

                <p>
                    Durch die Unterzeichnung des Aufnahmeantrags erkennt
                    der Bewerber die Satzung des Vereins an und
                    verzichtet ausdrücklich auf Klagen vor ordentlichen
                    Gerichten gegen Maßnahmen und Entscheidungen des
                    Vorstands, der Mitgliederversammlung und
                    Organisatoren. Er verpflichtet sich ferner, die
                    satzungsgemäßen Zwecke und Ziele des Vereins aktiv
                    zu fördern und sich am Vereinsleben rege zu
                    beteiligen.
                </p>

                <p>
                    Über den Aufnahmeantrag entscheidet der Vorstand
                    nach freiem Ermessen. Stimmengleichheit gilt als
                    Ablehnung. Bei Ablehnung des Antrags ist der
                    Vorstand nicht verpflichtet, dem Antragsteller die
                    Gründe mitzuteilen.
                </p>

                <p>
                    Nach Aufnahme beginnt die Mitgliedschaft mit der
                    Bezahlung der Aufnahmegebühr und des Beitrags.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-8"
            >
                <h2>§ 8 Pflichten der Mitglieder</h2>

                <p>
                    Beim Betrieb der Flugzeuge verpflichten sich die
                    Mitglieder, Professionalität walten zu lassen. Es
                    ist Aufgabe des Vereins, seine Mitglieder dabei zu
                    beraten und im Zweifelsfall Empfehlungen
                    festzulegen.
                </p>

                <p>
                    Das Mitglied nennt dem Verein ihm bekannte, günstige
                    Bezugsmöglichkeiten für Ersatzteile usw. und gibt
                    Erfahrungen und Tips kostenlos weiter.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-9"
            >
                <h2>§ 9 Beiträge</h2>

                <p>
                    Der Verein erhebt Beiträge, um die Ausgaben, die zur
                    Erfüllung der Ziele des Vereins notwendig sind,
                    bestreiten zu können.
                </p>

                <p>
                    Im Jahr 2000 und 2001 betragen die Beiträge in EURO
                    für
                </p>

                <div class="statute-fees">
                    <p>
                        ordentliche Mitglieder : € 500 pro Kalenderjahr
                    </p>

                    <p>
                        assoziierte Mitglieder : € 250 pro Kalenderjahr
                    </p>

                    <p>
                        fördernde Firmenmitglieder: € 2500 pro
                        Kalenderjahr
                    </p>

                    <p>
                        gegebenenfalls Ehrenmitglieder: kein Beitrag
                    </p>
                </div>

                <p>
                    Bei Eintritt in den Verein nach dem 30.06. des
                    Kalenderjahres wird für das laufende Jahr jeweils
                    die Hälfte des Jahresbeitrages erhoben.
                </p>

                <p>
                    Im Jahr 2001 wird in der Hauptversammlung die Höhe
                    des Jahresbeitrages für das Kalenderjahr 2002, und
                    in den Folgejahren entsprechend dieser Regelung von
                    den jeweiligen Hauptversammlungen der Beitrag nach
                    den aktuellen Erfordernissen jeweils für das nächste
                    Jahr festgelegt.
                </p>

                <p>
                    Der Jahresbeitrag ist bis zum 15. Februar des
                    betreffenden Kalenderjahres zu leisten.
                </p>

                <p>
                    Für die Verbindlichkeiten des Vereins haftet jedes
                    Mitglied maximal nur in Höhe seines fälligen
                    Jahresbeitrages.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-10"
            >
                <h2>§ 10 Ende der Mitgliedschaft</h2>

                <h3>Austritt</h3>

                <p>
                    a) Jedes Mitglied kann seinen Austritt per
                    Einschreiben zum Ende des Kalenderjahres erklären.
                    Das Kündigungsschreiben muß bis zum 30.9. beim
                    Vorstand eingegangen sein.
                </p>

                <p>
                    b) Mit dem Ablauf der Mitgliedschaft erlöschen
                    sämtliche Rechte und Ansprüche an den Verein, sein
                    Vermögen oder seine Einrichtungen.
                </p>

                <h3>Ausschluß</h3>

                <p>
                    Die Mitgliedschaft kann durch eine ordentliche oder
                    außerordentliche Hauptversammlung des Vereins mit
                    mindestens einer 2/3 Mehrheit der Anwesenden beendet
                    werden, wenn das Mitglied sich schwerwiegende
                    Verstöße gegen Zwecke und Ziele des Vereins, dessen
                    Satzung oder grob unkameradschaftliches Verhalten
                    zuschulden kommen läßt. Die Mitgliedschaft endet
                    auch, wenn das Mitglied trotz Mahnung mittels
                    Einschreibebrief/Rückschein mit seiner
                    Beitragszahlung länger als ein Vierteljahr im
                    Rückstand ist.
                </p>

                <p>
                    Der Ausschluß ist dem Mitglied an seine zuletzt
                    bekannte Adresse per Einschreiben mitzuteilen und
                    ist mit der Entscheidung wirksam. Ansprüche des
                    Vereins an das Mitglied enden nicht mit dem Ende der
                    Mitgliedschaft im Verein. Ansonsten gelten die
                    Bestimmungen von § 10 Absatz 1b.
                </p>
            </section>

