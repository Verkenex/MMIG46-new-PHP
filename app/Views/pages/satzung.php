            <section
                class="statute-paragraph"
                id="paragraph-12"
            >
                <h2>§ 12 Hauptversammlung der Mitglieder</h2>

                <p>
                    Die Hauptversammlung ist das oberste Organ des
                    Vereins . Die ordentliche Hauptversammlung findet in
                    der Regel im Mai eines jeden Kalenderjahres statt
                    und wird mindestens vier Wochen vorher vom
                    Vereinssprecher brieflich oder durch Veröffentlichung
                    auf den Internetseiten einberufen.
                </p>

                <p>
                    Stimmberechtigt mit je 1 Stimme sind alle anwesenden
                    volljährigen Mitglieder und Ehrenmitglieder.
                </p>

                <p>
                    Die Hauptversammlung wird geleitet vom
                    Vereinssprecher. Im Fall der Wahl eines neuen
                    Vereinssprechers übergibt der bisherige
                    Vereinssprecher seinem Nachfolger die Leitung der
                    Hauptversammlung.
                </p>

                <p>
                    Über die Ergebnisse der Hauptversammlung ist ein
                    Protokoll anzufertigen und auf den Internetseiten des
                    Vereins bekanntzugeben. Das Protokoll muß von 2
                    Vorstandsmitgliedern unterschrieben sein.
                </p>

                <p>
                    Anträge können von jedem Mitglied gestellt werden.
                    Die Anträge müssen mindestens 8 Tage vor der
                    Hauptversammlung beim Vorstand des Vereins
                    eingegangen sein. Über die Zulassung von
                    Dringlichkeitsanträgen, die spätestens vor Beginn der
                    Hauptversammlung dem Vorstand vorliegen müssen,
                    entscheidet der Vorstand mit Stimmenmehrheit.
                </p>

                <p>
                    Die Hauptversammlung ist zuständig für folgende
                    Tagesordnungspunkte:
                </p>

                <p>a) Bericht eines jeden Vorstandsmitglieds</p>
                <p>Bericht der Rechnungsprüfer</p>
                <p>Entlastung des Vorstandes (zusammen oder einzeln)</p>
                <p>Wahl des Vorstandes</p>
                <p>Wahl für Ersatz ausscheidender Vorstandsmitglieder</p>
                <p>Beitragsfestsetzung</p>
                <p>Satzungsänderung</p>
                <p>Auflösung des Vereins</p>
                <p>Beschlußfassung über alle vorliegenden Anträge</p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-13"
            >
                <h2>§ 13 Außerordentliche Hauptversammlungen</h2>

                <p>
                    Außerordentliche Hauptversammlungen sind unter
                    Angabe des Verhandlungsgegenstandes einzuberufen auf
                    Beschluß des Vorstandes, des Vereinssprechers oder
                    wenn mindestens 2/5 der Mitglieder des Vereins einen
                    diesbezüglichen Antrag schriftlich an den Sitz des
                    Vereins richten. Einladungen zur außerordentlichen
                    Hauptversammlung ergehen vom Vereinssprecher
                    schriftlich mit mindestens 14 Kalendertagen
                    Ladungsfrist unter Angabe der Tagesordnung.
                </p>

                <p>
                    Auch über die Ergebnisse der außerordentlichen
                    Hauptversammlung ist ein Protokoll anzufertigen und
                    den Mitgliedern bekanntzugeben. Das Protokoll muß von
                    2 Vorstandsmitgliedern unterschrieben sein.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-14"
            >
                <h2>§ 14 Abstimmungen</h2>

                <p>
                    Abstimmungen über Anträge erfolgen in der Regel
                    offen (durch Handzeichen).
                </p>

                <p>
                    Wahlen erfolgen grundsätzlich in offener Abstimmung
                    durch Handzeichen. Die Mitgliederversammlung kann
                    nur einstimmig beschließen, eine Wahl geheim
                    durchzuführen.
                </p>

                <p>
                    Jede Hauptversammlung ist ohne Rücksicht auf die Zahl
                    der erschienenen Stimmberechtigten beschlußfähig. Es
                    entscheidet regelmäßig einfache Stimmenmehrheit.
                    Unter einfacher Mehrheit ist eine Mehrheit zu
                    verstehen, die eine Stimme mehr beträgt als die
                    Hälfte der abgegebenen Stimmen. Stimmenenthaltungen
                    werden wie nicht abgegebene Stimmen behandelt,
                    ebenso abgegebene ungültige Stimmen und - bei
                    Abstimmung mit Stimmzetteln - unbeschriftete
                    Stimmzettel. Stimmengleichheit gilt als Ablehnung.
                </p>

                <p>
                    Zweidrittelmehrheit der abgegebenen Stimmen ist
                    erforderlich bei Beschlüssen über:
                </p>

                <p>a) Satzungsänderungen</p>

                <p>
                    b) Anträge auf Abberufung des Vorstandes oder eines
                    Vorstandsmitglieds
                </p>

                <p>c) Auflösung des Vereins.</p>

                <p>
                    Die Bestimmungen dieses Paragraphen gelten für alle
                    Abstimmungen, außer es ist ausdrücklich ein anderer
                    Modus festgelegt.
                </p>

                <p>
                    Briefwahl und Bevollmächtigung zur Wahl sind nicht
                    vorgesehen.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-15"
            >
                <h2>§ 15 Vorstand</h2>

                <p>
                    Der Vorstand darf nur von ordentlichen
                    Vereinsmitgliedern gebildet werden.
                </p>

                <p>
                    Der Vorstand umfaßt mindestens vier
                    Vorstandsmitglieder. Als Beisitzer können weitere
                    Mitglieder gewählt werden.
                </p>

                <p>
                    Der Vorstand im Sinne des §26 BGB setzt sich
                    zusammen aus
                </p>

                <p>a) dem Vereinssprecher,</p>

                <p>
                    b) seinem Stellvertreter als Geschäftsführer
                </p>

                <p>c) dem Schatzmeister und</p>

                <p>
                    Jedes Vorstandsmitglied verpflichtet sich, sein Amt
                    mit dem erforderlichen Einsatz und Zeitaufwand
                    auszuüben.
                </p>

                <p>
                    Vereinssprecher, Geschäftsführer und Schatzmeister
                    sind im Aussenverhältnis einzeln
                    vertretungsberechtigt.
                </p>

                <p>
                    Im Innenverhältnis gilt jedoch, daß der Stellvertreter
                    des Vereinssprechers nur im Falle der Verhinderung
                    des Vereinssprechers vertretungsberechtigt ist, der
                    Schatzmeister nur im Falle der Verhinderung sowohl
                    des Vereinssprechers als auch dessen Stellvertreters
                    und nur zusammen mit dem vierten Vorstandsmitglied.
                </p>

                <p>
                    Der Vorstand entscheidet in allen Angelegenheiten,
                    die nicht der Beschlußfassung der Hauptversammlung
                    unterliegen. Er leitet die gesamte Tätigkeit des
                    Vereins.
                </p>

                <p>
                    Die Vorstandsmitglieder werden von der
                    Hauptversammlung für die Dauer von 3 Jahren gewählt.
                    Eine Wiederwahl ist unbeschränkt möglich. Die
                    Amtsdauer rechnet sich von Hauptversammlung zur
                    entsprechenden Hauptversammlung.
                </p>

                <p>
                    Die Absetzung des Vorstandes oder einzelner
                    Mitglieder des Vorstandes kann nur erfolgen auf
                    Antrag von mehr als 2/3 der Mitglieder, die ein
                    Mißtrauensvotum vorbringen und in der
                    Hauptversammlung 2/3 - Mehrheit erhalten. Außerdem
                    kann der Vereinssprecher oder jedes einzelne Mitglied
                    des Vorstandes jederzeit zurücktreten.
                </p>

                <p>
                    Für vorzeitig ausscheidende Vorstandsmitglieder wird
                    dieses Amt in Personalunion von den verbleibenden
                    Vorstandsmitgliedern übernommen bis zur nächsten
                    Vorstandswahl.
                </p>

                <p>
                    Eine vorzeitige Neuwahl findet statt, wenn mindestens
                    2/3 der Mitglieder der außerordentlichen
                    Hauptversammlung dies fordert, die
                    Mitgliederversammlung dem Vorstand bzw. dem Ressort
                    die Entlastung nicht erteilt oder wenn die Mehrheit
                    des Vorstandes dies beantragt bzw. zurücktritt.
                </p>

                <p>
                    Der Vorstand kann sich eine Geschäftsordnung geben.
                </p>

                <p>
                    Der Vorstand ist beschlußfähig, wenn mindestens 3
                    Vorstandsmitglieder erschienen sind. Beschlüsse
                    werden mit einfacher Mehrheit gefaßt. Bei
                    Stimmgleichheit entscheidet die Stimme des
                    Vereinssprechers.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-16"
            >
                <h2>§ 16 Rechnungsprüfer</h2>

                <p>
                    Zwei Rechnungsprüfer werden abwechselnd von der
                    jährlichen Hauptversammlung aus dem Kreis der
                    Mitglieder gewählt. Ihre Amtszeit beträgt 2 Jahre.
                    Sie dürfen kein Amt im Vorstand bekleiden.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-17"
            >
                <h2>§ 17 Haftungsausschluß</h2>

                <p>
                    Mitglieder bzw. Teilnehmer, Helfer, Organisatoren,
                    Gäste, Familienangehörige nehmen selbstverantwortlich
                    auf eigene Gefahr an den Veranstaltungen teil.
                </p>

                <p>
                    Für alle von ihnen oder dem von ihnen benutzten
                    Luftfahrzeug verursachten Schäden tragen sie selbst
                    die zivil- und strafrechtliche Verantwortung.
                </p>

                <p>
                    Piloten müssen entweder Eigentümer oder Halter des
                    bei der Veranstaltung benutzten Luftfahrzeuges sein
                    oder ausdrücklich die alleinige Haftung für
                    eventuelle Forderungen des Eigentümers oder Halters
                    übernehmen und den Verein und Veranstalter von
                    solchen Ansprüchen unwiderruflich freistellen.
                </p>

                <p>
                    Es ist nicht Pflicht des Vereins bzw. des
                    Veranstalters, zu überprüfen, ob ein Pilot berechtigt
                    ist, das von ihm eingesetzte Luftfahrzeug für die
                    Veranstaltung zu nutzen.
                </p>

                <p>
                    Der Verein behält sich bei jeglichen Veranstaltungen
                    des Vereins das Recht vor, alle durch höhere Gewalt
                    oder aus Sicherheitsgründen oder von den Behörden
                    oder den für die jeweilige Flugstrecke
                    Verantwortlichen angeordneten oder erforderlichen
                    Änderungen angeordneten Änderungen einer
                    Veranstaltung vorzunehmen oder aber auch eine
                    Veranstaltung abzusagen.
                </p>

                <p>
                    Der Verein haftet nicht für Schadenersatzansprüche
                    hieraus und nicht für Aufwendungen aufgrund
                    geänderter Veranstaltungstermine und -orte oder
                    abgesagter Veranstaltungen.
                </p>

                <p>
                    Der Verein haftet nicht für die Richtigkeit
                    technischer Bewertungen, Wartungsempfehlungen oder
                    sonstiger Hinweise und Beurteilungen in Bezug auf
                    Wartung und Betrieb des Luftfahrtgerätes.
                </p>

                <p>
                    Soweit dies nicht gesondert zum Ausdruck gebracht
                    wird, sind solche Bewertungen und Empfehlungen als
                    freie Meinungsäußerung im Sinne der Pressefreiheit zu
                    verstehen.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-18"
            >
                <h2>§ 18 Satzungsänderungen</h2>

                <p>
                    Anträge auf Satzungsänderungen können nicht als
                    Dringlichkeitsanträge gestellt werden. Sie werden
                    vom Vorstand geprüft und der Hauptversammlung
                    vorgelegt. Diese entscheidet mit Zweidrittelmehrheit
                    der abgegebenen Stimmen der anwesenden Mitglieder.
                </p>
            </section>

            <section
                class="statute-paragraph"
                id="paragraph-19"
            >
                <h2>§ 19 Auflösung des Vereins</h2>

                <p>
                    Die Auflösung des Vereins kann nur auf einer eigens
                    zu diesem Zweck einberufenen außerordentlichen
                    Hauptversammlung oder auf der regulären
                    Jahres-Hauptversammlung beschlossen werden.
                </p>

                <p>
                    Der Auflösungsbeschluß bedarf der Zustimmung einer
                    2/3 Mehrheit der anwesenden Mitglieder. Ist die
                    außerordentliche Hauptversammlung nicht
                    beschlußfähig, so ist eine anschließend mit
                    satzungsmäßiger Frist einberufene Hauptversammlung in
                    jedem Fall beschlußfähig, wobei die einfache
                    Mehrheit der Hauptversammlung entscheidet.
                </p>

                <p>
                    Diese außerordentliche Hauptversammlung (zwecks
                    Auflösung) bestimmt den Liquidator mit 2/3 Mehrheit
                    der anwesenden Mitglieder.
                </p>

                <p>
                    Das bei Auflösung vorhandene Vermögen ist nach
                    Tilgung aller Verbindlichkeiten an eine vom
                    Liquidator zu bestimmende und als gemeinnützig
                    anerkannte Einrichtung des
                    Verkehrs-/Kraftfahrzeug-Wesens abzuführen.
                </p>
            </section>

