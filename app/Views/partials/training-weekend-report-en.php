            <h2>Friday</h2>

            <p>On Friday, 25 September, and Saturday, 26 September 2026, the MMIG 46 training weekend took place at Mönchengladbach Airport, in the RAS facilities, on the apron and in the MGFlyers simulator.</p>
            <p>From late morning onwards, aircraft began arriving and were parked in the reserved areas A5 and A6 on the apron at Mönchengladbach Airport.</p>
            <p>Max Buchholz from EDLN airport operations had arranged, by NOTAM, for this space to remain reserved exclusively for participants in the event on both days.</p>
            <p>The airport also made a very generous gesture by waiving parking fees and halving landing fees.</p>
            <p>A big thank you to RAS and Frank Prochaska:<br>RAS provided all the rooms and facilities we needed, as well as drinks and filled rolls.</p>
            <p>Frank’s son Tom, currently a working student at RAS, transported those arriving from the apron to RAS and then, every hour, also to MgFlyers, where the new Alsim AL250 simulator was in constant use.</p>
            <p>This meant that everyone could spend an hour in the simulator. Klaus Hohnen and Dennis Viehoff provided professional training for our members.</p>
            <p>Quite a few participants, who were able to experience all sorts of extreme situations in the simulator without any risk, returned to the seminar room feeling a little dizzy after their session.</p>
            <p>Thanks also to Julian Goldau and Max Gerecht, who handled the communications and public relations via the internet and messaging services in advance, made the name badges and produced the new MMIG 46 polo shirts.</p>
            <p>Alongside my full-time work in the practice, I could never have managed all of this!</p>
            <p>The polo shirts were well received.</p>
            <p>If you are interested, we have more in stock at €40 plus shipping costs — just ask.</p>
