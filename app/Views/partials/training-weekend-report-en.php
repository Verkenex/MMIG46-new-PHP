        <div class="recap-prose">
            <p>The individual demonstration of the airport fire service’s large fire engine by its chief, Mr Hensen, was eagerly awaited.</p>
            <p>In glorious weather, the fire engine, which costs millions, was demonstrated on the apron in front of RAS.</p>
            <p>Its capabilities are enormous:<br>It can project up to 5,000 litres of water per minute over a distance of more than 60 metres.</p>
            <p>We learned a great deal about tactics in the event of an aircraft fire and were shown the wide range of extremely powerful tools used to open up crumpled metal panels in order to rescue people from dangerous situations caused by fire.</p>
            <p>Frank Lumnitzer and Ralph Wendt had offered to conduct training flights as early as Friday afternoon. Interested pilots were quickly found, and planning began, followed by the flights themselves.</p>
            <p>Meanwhile, Fabian Kienzle demonstrated Garmin’s latest range of equipment, Axis, to interested members.</p>
            <p>From 17:00, Norbert Klippel gave us a very detailed and personal talk about seaplane flying in Germany.</p>
            <p>Norbert’s career, his enthusiasm for flying and his lifetime achievements can only serve as an example to a younger generation.</p>
            <p>We listened spellbound to his accounts and ultimately came away with the feeling that, even in Germany, anything is still possible, provided you want to achieve something and have the energy and discipline to see it through.</p>
            <p>Thank you once again for this outstanding and inspiring talk.</p>
