            <h2>Saturday</h2>
            <p>On Saturday morning, we met outside the seminar room from 08:30 for coffee and our first conversations of the day.</p>
            <p>From 09:00, further hourly sessions took place in the flight simulator at MgFlyers.</p>
            <p>After a brief introduction by Klaus Gerecht, Frank Lumnitzer began his highly engaging explanations of the principles behind IFR approach design and the extent of the protected areas in three-dimensional space.</p>
            <p>Who among us has ever looked in detail at the temperature variables affecting LNAV approaches? Until then, hardly anyone seemed to have realised that cold temperatures can pose considerable risks to obstacle clearance.</p>
            <p>So, better to use LPV or ILS when available.</p>
            <p>Speaking on the subject of “New developments in Garmin avionics and PA46-specific retrofits”, Fabian Kienzle explained the new product range called Axis.</p>
            <p>With 11.6- and 8-inch displays, it is possible to install fully integrated avionics in older aircraft. If you still love your avionics stack, there are versions that serve purely as displays.</p>
            <p>Other advantages include lower weight, substantially less wiring and, on the software side, features such as widgets, programmable touch buttons along the edge that quickly bring up submenus on the PFD, a 3D view while taxiing, or a warning about an aircraft on the runway while you are on approach.</p>
            <p>At the same time, Frank Lumnitzer and Ralph Wendt conducted many training flights with interested members.</p>
            <p>In the afternoon, we heard several talks by Michael Offermann on the following topics:</p>
            <ol class="recap-topics"><li>“Murphy’s Law” is why simulator training makes sense for non-commercial pilots too</li><li>Never bring your “stress from outside the aviation environment” on board, even if I explain how to deal with it</li><li>The 30 most important medical issues that should always be discussed with an aviation medical examiner</li></ol>
            <p>Through his talks, Michael managed to draw us into the fascinating world of managing stress through training, often with humorous interludes.</p>
            <p>Later in the afternoon, the first members flew back towards their home bases, while the popular simulator sessions continued until well after 18:00.</p>
            <p>Two interesting days came to an end, and the feedback suggests that we all benefited in terms of our own flight safety.</p>
            <p>New connections were made and many interesting conversations took place — not only during the cheerful social evening in the Ramshof’s Oval Office.</p>
