        <div class="recap-prose">
            <p>Mit Spannung erwartet wurde die individuelle Demonstration der Flughafenfeuerwehr mit großem Einsatzfahrzeug durch deren Leiter, Herrn Hensen.</p>
            <p>Bei bestem Wetter wurde auf dem Vorfeld vor der RAS das millionenteure Einsatzfahrzeug demonstriert.</p>
            <p>Die Leistungsfähigkeit ist enorm:<br>Bis zu 5.000 l/min Wasser können über 60 m weit geschleudert werden.</p>
            <p>Wir lernten viel über die Taktik im Fall eines brennenden Flugzeugs und bekamen einen Einblick in die Vielzahl der extrem starken Instrumente zum Öffnen verbeulter Blechteile, um Menschen aus feuerbedingter prekärer Lage befreien zu können.</p>
            <p>Frank Lumnitzer und Ralph Wendt hatten sich bereit erklärt, auch schon am Freitagnachmittag Trainingsflüge durchzuführen. Schnell fanden sich interessierte Piloten, und die Planung und anschließende Durchführung begann.</p>
            <p>Derweil demonstrierte Fabian Kienzle interessierten Mitgliedern die neueste Geräteserie von Garmin: Axis.</p>
            <p>Ab 17:00 Uhr informierte uns Norbert Klippel in einem sehr ausführlichen und persönlich gehaltenen Vortrag über das Wasserflugzeugfliegen in Deutschland.</p>
            <p>Der Werdegang von Norbert, seine Flugbegeisterung und seine Lebensleistung können nur Vorbild für eine junge Generation sein.</p>
            <p>Gebannt hörten wir seinen Schilderungen zu und bekamen letztlich das Gefühl vermittelt, dass selbst in Deutschland noch alles machbar ist, vorausgesetzt, man will etwas erreichen und hat die Energie und Disziplin, das durchzuziehen.</p>
            <p>Nochmals danke für diesen hervorragenden und mitreißenden Vortrag.</p>
