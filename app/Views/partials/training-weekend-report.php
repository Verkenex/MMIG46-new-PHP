            <h2>Freitag</h2>

            <p>Am Freitag, den 25. September, und Samstag, den 26. September 2026, fand das Trainingswochenende der MMIG 46 auf dem Flughafen Mönchengladbach in den Räumen der RAS, auf dem Vorfeld und im Simulator der MGFlyers statt.</p>
            <p>Ab dem späten Vormittag landeten die Maschinen und wurden auf den reservierten Feldern A5 und A6 auf dem Vorfeld des Flughafens Mönchengladbach geparkt.</p>
            <p>Max Buchholz von der Flugleitung EDLN hatte per NOTAM dafür gesorgt, dass dieser Platz exklusiv für die Teilnehmer der Veranstaltung an beiden Tagen reserviert blieb.</p>
            <p>Ein großes Entgegenkommen seitens des Flughafens war außerdem die Suspendierung der Abstellgebühren in Verbindung mit der Halbierung der Landegebühren.</p>
            <p>Großer Dank an die RAS und Frank Prochaska:<br>Alle benötigten Räume und Einrichtungen sowie Getränke und belegte Brötchen wurden von der RAS zur Verfügung gestellt.</p>
            <p>Franks Sohn Tom, zurzeit Werkstudent bei RAS, sorgte für den Transport der Anreisenden vom Vorfeld zur RAS und dann im Stundentakt auch zu MgFlyers, wo der neue Simulator Alsim AL250 ununterbrochen in Verwendung war.</p>
            <p>So konnte jeder eine Stunde im Simulator verbringen. Klaus Hohnen und Dennis Viehoff sorgten für professionelles Training unserer Mitglieder.</p>
            <p>So mancher Kandidat, der sich risikofrei im Simulator allen möglichen Extremsituationen aussetzen konnte, kam mit leichtem Schwindel nach der Sitzung wieder in den Seminarraum.</p>
            <p>Dank auch an Julian Goldau und Max Gerecht, die im Vorfeld für die Kommunikation, Public Relations über Internet und Kurznachrichtendienste, Herstellung der Namensschilder und Produktion der neuen MMIG 46-Polohemden verantwortlich waren.</p>
            <p>Neben meiner Vollzeittätigkeit in der Praxis hätte ich das nie geschafft!</p>
            <p>Die Polohemden fanden guten Anklang.</p>
            <p>Bei Interesse gibt es weitere Exemplare im Lager zum Preis von 40 € + Versandkosten auf Zuruf.</p>
