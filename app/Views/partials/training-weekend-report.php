    <section class="recap-section" id="recap-samstag">
        <div class="recap-prose">
            <h2>Samstag</h2>
            <p>Am Samstagmorgen trafen wir uns ab 08:30 Uhr vor dem Seminarraum zum Kaffee und ersten Gesprächen.</p>
            <p>Ab 09:00 Uhr fanden stündlich weitere Sitzungen im Flugsimulator bei MgFlyers statt.</p>
            <p>Nach einer kurzen Einführung durch Klaus Gerecht begann Frank Lumnitzer mit seinen hochinteressanten Ausführungen zu den Hintergründen der Planung von IFR-Anflügen und der Ausdehnung der Sicherheitsbereiche im Raum.</p>
            <p>Wer von uns hat sich jemals detailliert mit den Temperaturvariablen von LNAV-Anflügen auseinandergesetzt? Dass hier bei kalten Temperaturen erhebliche Risiken in Hinblick auf die Hindernisfreiheit entstehen können, war wohl kaum jemandem klar bisher.</p>
            <p>Also lieber LPV oder ILS, wenn verfügbar.</p>
            <p>Fabian Kienzle erläuterte zum Thema „Neuheiten Garmin-Avionik und spezifische PA46-Nachrüstung“ die neue Produktreihe namens Axis.</p>
            <p>Auf 11,6- und 8-Zoll-Bildschirmen ist es möglich, in älteren Maschinen voll integrierte Avionik zu installieren. Wenn man seinen Avionics Stack weiter liebt, gibt es Versionen, die lediglich als Anzeigetafeln dienen.</p>
            <p>Weitere Vorteile sind das geringere Gewicht, die absolut geringere Menge an Verkabelung und softwareseitig zum Beispiel Widgets, programmierbare Tastfelder am Rande, über die rasch Untermenüs auf dem PFD aktiviert werden, die 3-D-Darstellung beim Rollen oder die Warnung vor einem auf der Landebahn befindlichen Luftfahrzeug, während man sich im Anflug befindet.</p>
            <p>Parallel führten Frank Lumnitzer und Ralph Wendt viele Trainingsflüge mit interessierten Mitgliedern durch.</p>
            <p>Am Nachmittag hörten wir mehrere Vorträge von Michael Offermann zu den Themen:</p>
            <ol class="recap-topics"><li>„Murphys Law“ ist der Grund für die Sinnhaftigkeit von Simulatortraining auch bei nicht kommerziellen Piloten</li><li>Niemals Euren „nicht systemimmanenten Stress“ mit an Bord nehmen, auch wenn ich Euch erkläre, wie damit umzugehen ist</li><li>Die wichtigsten 30 medizinischen Probleme, die in jedem Fall mit einem Fliegerarzt zu besprechen wären</li></ol>
            <p>Michael hat es verstanden, uns mit seinen Vorträgen in die faszinierende Welt der Stresskontrolle durch Training zu führen, oft mit humorvollen Einlagen.</p>
            <p>Am späteren Nachmittag flogen dann die ersten Mitglieder wieder Richtung Heimatbasis, während die beliebten Simulator-Sitzungen noch bis weit nach 18:00 Uhr andauerten.</p>
            <p>Zwei interessante Tage gingen zu Ende, und viele Rückmeldungen deuten darauf hin, dass wir alle in Hinblick auf unsere eigene Flugsicherheit davon profitiert haben.</p>
            <p>Neue Verbindungen wurden geknüpft, viele interessante Gespräche geführt – nicht nur an dem von heiterer Stimmung getragenen Gesellschaftsabend im Oval Office des Ramshofes.</p>
