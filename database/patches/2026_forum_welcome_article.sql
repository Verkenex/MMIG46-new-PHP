Das gilt insbesondere bei:

- persönlichen Angriffen,
- diskriminierenden oder beleidigenden Aussagen,
- Veröffentlichung vertraulicher Informationen,
- rechtlich problematischen Inhalten,
- Spam oder Werbung,
- wiederholtem themenfremdem Verhalten.

Moderation ist kein persönlicher Angriff, sondern dient dem Schutz des Forums und der Mitglieder.

