Bitte behandeln Sie andere Mitglieder so, wie Sie es auch im persönlichen Gespräch auf einem Fly-In, bei einer Mitgliederversammlung oder im Hangar tun würden.

- Schreiben Sie höflich, klar und ohne persönliche Angriffe.
- Kritik ist willkommen, solange sie sachbezogen und nachvollziehbar formuliert ist.
- Ironie, politische Seitenhiebe und abwertende Bemerkungen führen online schnell zu Missverständnissen und sollten vermieden werden.
