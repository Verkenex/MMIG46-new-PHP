- das POH oder AFM,
- offizielle Wartungsunterlagen,
- Anweisungen des Herstellers,
- Vorgaben von Behörden,
- die Einschätzung eines lizenzierten Wartungsbetriebs,
- die Arbeit eines Fluglehrers, Prüfers oder verantwortlichen Piloten.

