Bitte veröffentlichen Sie keine personenbezogenen oder vertraulichen Informationen ohne ausdrückliche Zustimmung.

Dazu gehören insbesondere:

- vollständige Namen Dritter,
- Telefonnummern, E-Mail-Adressen oder Privatadressen,
- Kennzeichen, wenn der Bezug zu Personen oder Eigentümern problematisch sein kann,
- Rechnungen, Verträge, Wartungsdokumente oder Logbuchauszüge,
- interne Vereinsinformationen,
- nicht öffentliche Informationen über Flugplätze, Betriebe oder einzelne Personen.

Wenn Sie Fotos, Screenshots oder Dokumente hochladen, prüfen Sie diese vorher sorgfältig auf sichtbare Namen, Nummern, Metadaten und vertrauliche Details.

